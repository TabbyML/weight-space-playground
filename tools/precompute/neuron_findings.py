"""Step 7: analysis of the cached neuron traces -> tools/precompute/out/neuron-findings.md.

    python -m tools.precompute.neuron_findings

Reads the full-precision per-run caches written by ``neuron_trace`` (not the quantised served
files) plus replay.json (loop segments, thinkEnd) and the raw llama-server recordings (for the
recorded top-1 rate used as a sanity reference).
"""
from __future__ import annotations

import json

import numpy as np

from . import config, loops
from . import neuron_trace as nt

ONSET_WINDOWS = ((-1024, -512), (-512, 0), (0, 512), (512, 1024))
STOP_WINDOW = 256


# ---------- pure helpers ----------

def loop_mask(n: int, loops: list[dict]) -> np.ndarray:
    """Boolean [n]: token inside any [start, end) loop segment."""
    m = np.zeros(n, dtype=bool)
    for s in loops:
        m[s["start"]:s["end"]] = True
    return m


def union_loop_mask(tokens: list) -> np.ndarray:
    """Boolean [n]: token inside ANY qualifying periodic span of loops.find_loops (overlaps allowed)."""
    m = np.zeros(len(tokens), dtype=bool)
    for p in range(4, min(400, len(tokens) // 2) + 1):
        for s, e in loops.periodic_spans(tokens, p):
            if e - s >= max(48, 3 * p):
                m[s:e] = True
    return m


def window_mean(x: np.ndarray, anchor: int, lo: int, hi: int) -> float | None:
    """Mean of x[anchor+lo : anchor+hi] clipped to the array; None if the window is empty."""
    a, b = max(0, anchor + lo), min(len(x), anchor + hi)
    return float(np.mean(x[a:b])) if b > a else None


def effect_size(inside: np.ndarray, outside: np.ndarray) -> float:
    """(mean_in - mean_out) / pooled std (Cohen's d)."""
    vi, vo = np.var(inside, ddof=1), np.var(outside, ddof=1)
    pooled = np.sqrt(((len(inside) - 1) * vi + (len(outside) - 1) * vo) / (len(inside) + len(outside) - 2))
    return float((inside.mean() - outside.mean()) / pooled) if pooled > 0 else 0.0


def channel_shares(a: np.ndarray, w: np.ndarray) -> np.ndarray:
    """Share of each channel in sum_k |mean_t(w_k a_k)| (sums to 1)."""
    contrib = np.abs((np.asarray(a, dtype=np.float64) * w).mean(axis=0))
    return contrib / contrib.sum()


def n_for_share(shares: np.ndarray, frac: float) -> int:
    """Smallest number of channels whose shares reach `frac`."""
    return int(np.searchsorted(np.cumsum(np.sort(shares)[::-1]), frac - 1e-12) + 1)


def fmt(x: float | None, d: int = 2) -> str:
    return "–" if x is None else f"{x:.{d}f}"


# ---------- analysis ----------

def recorded_top1(case: dict, stream: str) -> float:
    raw = nt.raw_recording(case, stream)
    probs = raw["response"]["completion_probabilities"]
    return float(np.mean([p["top_logprobs"][0]["id"] == p["id"] for p in probs]))


def analyse() -> str:
    replay = nt.load_replay()
    edits = nt.edit_tensors()
    w = {L: edits[L]["w"] for L in nt.LAYERS}
    cols = {L: edits[L]["cols"] for L in nt.LAYERS}
    data = {}
    for c in replay["cases"]:
        recs, lps, metas = {}, {}, {}
        for r in nt.RUNS:
            arrs, meta = nt.load_cached(c, r)
            recs[r], lps[r], metas[r] = nt.run_record(arrs, w), arrs["logprob"].astype(np.float64), meta
        data[c["id"]] = (c, recs, lps, metas)
    loop_cases = [c for c in replay["cases"] if c["kind"] == "loop"]
    ctrl = [c for c in replay["cases"] if c["kind"] == "control"]
    L_ = nt.LAYERS
    out: list[str] = []
    w_ = out.append

    meta0 = next(iter(data.values()))[3]["base"]
    w_("# Neuron trace findings (bf16, teacher-forced)\n")
    w_(f"Generated by `python -m tools.precompute.neuron_findings` from the full-precision caches of "
       f"`neuron_trace` (transformers {meta0['versions']['transformers']}, torch {meta0['versions']['torch']}, "
       f"{meta0['versions']['gpu']}). Cases: the {len(replay['cases'])} replay cases "
       f"({len(loop_cases)} loop, {len(ctrl)} control). Definitions (per generated token, per layer):\n")
    w_("- **push** = u · (Δ a): the edit's added down_proj output along its residual direction u "
       "(Δ = edited − base, exact bf16; a = the 64 edited intermediate activations). For the base run it is "
       "hypothetical (what the edit *would* add given the base's activations).")
    w_("- **proj** = u · y: projection of the full down_proj output (all 3584 neurons, the run's own weights) on u.")
    w_("- **norm** = ‖a[64 edited columns]‖₂.")
    w_("- Runs: **base** (base weights, base tokens), **edited** (edited weights, edited tokens), "
       "**cf** = counterfactual (edited weights over the base tokens).")
    w_("- Sign of u is the SVD convention of weight-diff.json; the edit is w_j' = w_j − α(u·w_j)u with α≈6, so "
       "push = −α·(u-component written by the 64 neurons under base weights): the edit flips that component "
       "and scales it by (1−α) ≈ −5. A push of the opposite sign to the base's proj is the edit pushing back.\n")

    # ---- 1. inside vs outside loops (base run)
    w_("## 1. Base run: inside vs outside the recorded loop segments\n")
    w_("Means over tokens. `in` = inside `replay.json` loop segments, `out` = all other generated tokens, "
       "d = Cohen's d (in − out).\n")
    w_("| case | loop tokens | layer | push in | push out | ratio | d | proj in | proj out | norm in | norm out |")
    w_("|---|---|---|---|---|---|---|---|---|---|---|")
    agg = {L: {"in": [], "out": []} for L in L_}
    for c in loop_cases:
        _, recs, _, _ = data[c["id"]]
        n = c["base"]["nTokens"]
        m = loop_mask(n, c["base"]["loops"])
        for L in L_:
            r = recs["base"][L]
            pi, po = r["push"][m], r["push"][~m]
            agg[L]["in"].append(pi)
            agg[L]["out"].append(po)
            w_(f"| {c['id']} | {m.sum()} / {n} | {L} | {pi.mean():.2f} | {po.mean():.2f} | {pi.mean() / po.mean():.2f} "
               f"| {effect_size(pi, po):.2f} | {r['proj'][m].mean():.2f} | {r['proj'][~m].mean():.2f} "
               f"| {r['norm'][m].mean():.2f} | {r['norm'][~m].mean():.2f} |")
    for c in ctrl:
        _, recs, _, _ = data[c["id"]]
        for L in L_:
            r = recs["base"][L]
            w_(f"| {c['id']} (control, no loop) | 0 / {len(r['push'])} | {L} | – | {r['push'].mean():.2f} | – | – "
               f"| – | {r['proj'].mean():.2f} | – | {r['norm'].mean():.2f} |")
    pooled = {L: (np.concatenate(agg[L]["in"]), np.concatenate(agg[L]["out"])) for L in L_}
    w_("")
    for c in loop_cases:
        u = union_loop_mask(c["base"]["tokens"])
        m = loop_mask(c["base"]["nTokens"], c["base"]["loops"])
        if u.sum() == m.sum():
            continue
        recs = data[c["id"]][1]["base"]
        w_(f"- Loop-detector gap, {c['id']}: `loops.find_loops` keeps only non-overlapping spans and drops an "
           f"overlapping verbatim span, so replay.json marks {m.sum()} loop tokens while the union of all "
           f"qualifying periodic spans is {u.sum()}. With the union mask: push in / out = "
           + "; ".join(f"L{L} {recs[L]['push'][u].mean():.2f} / {recs[L]['push'][~u].mean():.2f}" for L in L_)
           + " (the table above uses replay.json's segments).")
    w_("")
    for L in L_:
        pi, po = pooled[L]
        w_(f"- Pooled over the {len(loop_cases)} loop cases, layer {L}: push in {pi.mean():.2f} vs out {po.mean():.2f} "
           f"(×{pi.mean() / po.mean():.2f}, d = {effect_size(pi, po):.2f}); |push| in {np.abs(pi).mean():.2f} vs out "
           f"{np.abs(po).mean():.2f}.")
    w_("")

    # ---- 2. loop onset
    w_("## 2. Around the loop onset (base run)\n")
    w_("Mean push in token windows relative to the start of the **first** loop segment and of the **longest** "
       "(final, runs to the cap) segment. Windows: " + ", ".join(f"[{a},{b})" for a, b in ONSET_WINDOWS) + ".\n")
    w_("| case | anchor | start | layer | " + " | ".join(f"[{a},{b})" for a, b in ONSET_WINDOWS) + " |")
    w_("|---|---|---|---|" + "---|" * len(ONSET_WINDOWS))
    for c in loop_cases:
        _, recs, _, _ = data[c["id"]]
        loops = c["base"]["loops"]
        anchors = {"first": loops[0]["start"], "longest": max(loops, key=lambda s: s["end"] - s["start"])["start"]}
        for name, s in anchors.items():
            if name == "longest" and s == anchors["first"]:
                continue
            for L in L_:
                vals = [window_mean(recs["base"][L]["push"], s, a, b) for a, b in ONSET_WINDOWS]
                w_(f"| {c['id']} | {name} | {s} | {L} | " + " | ".join(fmt(v) for v in vals) + " |")
    w_("")
    # position confound: loops sit late in the run; is push simply growing with position?
    w_("Position check (loops sit late in the run): mean layer-15 / layer-19 push per 2048-token block for the "
       "base run (with its loop share) and the edited run, which has no long loop.\n")
    blocks = list(range(0, 16384, 2048))
    w_("| case | run | " + " | ".join(f"{b // 1024}k" for b in blocks) + " |")
    w_("|---|---|" + "---|" * len(blocks))
    for c in loop_cases:
        _, recs, _, _ = data[c["id"]]
        m = loop_mask(c["base"]["nTokens"], c["base"]["loops"])
        for r in ("base", "edited"):
            cells = []
            for b in blocks:
                p15 = recs[r][15]["push"][b:b + 2048]
                if not len(p15):
                    cells.append("–")
                    continue
                p19 = recs[r][19]["push"][b:b + 2048]
                cell = f"{p15.mean():.2f} / {p19.mean():.2f}"
                if r == "base":
                    cell += f" ({m[b:b + 2048].mean() * 100:.0f}% loop)"
                cells.append(cell)
            w_(f"| {c['id']} | {r} | " + " | ".join(cells) + " |")
    w_("")
    # per-period structure inside the longest loop: within-period variation vs between-period
    w_("Inside a loop the trace is periodic like the text: the std of push across one period (within-period "
       "variation) vs the std of the per-period means (drift across repeats), longest segment:\n")
    w_("| case | period | layer | within-period std | std of period means | first-period mean | last-period mean |")
    w_("|---|---|---|---|---|---|---|")
    for c in loop_cases:
        _, recs, _, _ = data[c["id"]]
        s = max(c["base"]["loops"], key=lambda s: s["end"] - s["start"])
        p = s["period"]
        k = (s["end"] - s["start"]) // p
        for L in L_:
            x = recs["base"][L]["push"][s["start"]:s["start"] + k * p].reshape(k, p)
            w_(f"| {c['id']} | {p} | {L} | {x.std(axis=1).mean():.2f} | {x.mean(axis=1).std():.3f} "
               f"| {x[0].mean():.2f} | {x[-1].mean():.2f} |")
    w_("")

    # ---- 3. base vs counterfactual
    w_("## 3. Base vs counterfactual (edited weights over the base tokens)\n")
    w_("Layer 15's inputs are identical in both (layers < 15 are unchanged), so its push is identical and its "
       "proj differs by exactly the push. Layer 19 sees the edited layer 15 upstream. `lp` = mean bf16 "
       "log-prob of the recorded base tokens under each weight set.\n")
    w_("| case | segment | L15 proj base → cf | L19 push base → cf | L19 proj base → cf | L19 norm base → cf "
       "| lp base → cf |")
    w_("|---|---|---|---|---|---|---|")
    for c in loop_cases + ctrl:
        _, recs, lps, _ = data[c["id"]]
        n = c["base"]["nTokens"]
        m = loop_mask(n, c["base"]["loops"])
        segs = (("in loops", m), ("outside", ~m)) if m.any() else (("all", ~m),)
        for name, mm in segs:
            b, f = recs["base"], recs["counterfactual"]
            w_(f"| {c['id']} | {name} | {b[15]['proj'][mm].mean():.2f} → {f[15]['proj'][mm].mean():.2f} "
               f"| {b[19]['push'][mm].mean():.2f} → {f[19]['push'][mm].mean():.2f} "
               f"| {b[19]['proj'][mm].mean():.2f} → {f[19]['proj'][mm].mean():.2f} "
               f"| {b[19]['norm'][mm].mean():.2f} → {f[19]['norm'][mm].mean():.2f} "
               f"| {lps['base'][mm].mean():.3f} → {lps['counterfactual'][mm].mean():.3f} |")
    lp_b = np.concatenate([data[c["id"]][2]["base"][loop_mask(c["base"]["nTokens"], c["base"]["loops"])]
                           for c in loop_cases])
    lp_f = np.concatenate([data[c["id"]][2]["counterfactual"][loop_mask(c["base"]["nTokens"], c["base"]["loops"])]
                           for c in loop_cases])
    w_("")
    w_(f"- Pooled loop tokens (n = {lp_b.size}): mean log-prob {lp_b.mean():.4f} (base) vs {lp_f.mean():.4f} (cf); "
       f"share of loop tokens with p < 0.5: {np.mean(lp_b < np.log(0.5)):.4f} (base) vs "
       f"{np.mean(lp_f < np.log(0.5)):.4f} (cf); p < 0.9: {np.mean(lp_b < np.log(0.9)):.4f} vs "
       f"{np.mean(lp_f < np.log(0.9)):.4f}.\n")

    # ---- 4. edited run near its stop
    w_("## 4. Edited run near its stop\n")
    w_(f"Mean push / norm in the edited run: whole thinking span, the last {STOP_WINDOW} thinking tokens before "
       f"`</think>`, the answer span after it (ends at EOS), and the base run at the same token positions.\n")
    w_("| case | thinkEnd / n | layer | push thinking | push last 256 before </think> | push answer "
       "| norm thinking | norm answer | base push, same positions as edited answer |")
    w_("|---|---|---|---|---|---|---|---|---|")
    for c in loop_cases + ctrl:
        _, recs, _, _ = data[c["id"]]
        te, n = c["edited"]["thinkEnd"], c["edited"]["nTokens"]
        for L in L_:
            e = recs["edited"][L]
            bpush = recs["base"][L]["push"]
            same = bpush[te:n].mean() if n <= len(bpush) else None
            w_(f"| {c['id']} | {te} / {n} | {L} | {e['push'][:te].mean():.2f} "
               f"| {fmt(window_mean(e['push'], te, -STOP_WINDOW, 0))} | {e['push'][te:].mean():.2f} "
               f"| {e['norm'][:te].mean():.2f} | {e['norm'][te:].mean():.2f} | {fmt(same)} |")
    c0 = data["math500-algebra-2551"][0] if "math500-algebra-2551" in data else None
    if c0 and c0["edited"]["loops"]:
        s = c0["edited"]["loops"][0]
        recs = data[c0["id"]][1]
        m = loop_mask(c0["edited"]["nTokens"], c0["edited"]["loops"])
        w_("")
        w_(f"- The one edited run with a short loop ({c0['id']}, tokens {s['start']}–{s['end']}, period "
           f"{s['period']}, {s['repeats']} repeats) then escapes: push inside it L15 "
           f"{recs['edited'][15]['push'][m].mean():.2f} / L19 {recs['edited'][19]['push'][m].mean():.2f} vs rest "
           f"{recs['edited'][15]['push'][~m].mean():.2f} / {recs['edited'][19]['push'][~m].mean():.2f}.")
    w_("")

    # ---- 5. channels
    w_("## 5. Which channels dominate\n")
    w_("Share of each channel in Σ_k |mean_t(pushWeight_k · a_k)| over all base-run loop tokens of the loop "
       "cases, and the channels that carry the in-loop *increase* of push (pushWeight_k · (mean a_k in − mean "
       "a_k out)). Channel = intermediate neuron id (column of down_proj).\n")
    for L in L_:
        a_in = np.concatenate([data[c["id"]][1]["base"][L]["a"][loop_mask(c["base"]["nTokens"], c["base"]["loops"])]
                               for c in loop_cases])
        a_out = np.concatenate([data[c["id"]][1]["base"][L]["a"][~loop_mask(c["base"]["nTokens"], c["base"]["loops"])]
                                for c in loop_cases])
        sh = channel_shares(a_in, w[L])
        top = np.argsort(sh)[::-1][:5]
        inc = w[L] * (a_in.mean(axis=0) - a_out.mean(axis=0))
        top_inc = np.argsort(-np.abs(inc))[:5]
        w_(f"- Layer {L}: {n_for_share(sh, 0.5)} channels carry 50% and {n_for_share(sh, 0.8)} carry 80% of the "
           f"in-loop push magnitude. Top 5: " + ", ".join(f"#{cols[L][k]} ({sh[k] * 100:.1f}%)" for k in top) + ".")
        w_(f"  In-loop increase of push ({inc.sum():.2f} total): top contributors "
           + ", ".join(f"#{cols[L][k]} ({inc[k]:+.2f})" for k in top_inc) + ".")
    w_("")

    # ---- sanity
    w_("## Sanity: does the bf16 forward reproduce the recordings?\n")
    w_("bf16 top-1 agreement = share of recorded tokens that are the bf16 argmax at their position; the "
       "recorded rate is the same share under the Q4_K_M llama.cpp distribution that sampled them "
       "(temperature 0.6, so < 1 is expected).\n")
    w_("| case | run | n | bf16 top-1 | recorded (Q4_K_M) top-1 | bf16 mean log-prob | forward s |")
    w_("|---|---|---|---|---|---|---|")
    for c in replay["cases"]:
        _, _, _, metas = data[c["id"]]
        for r in nt.RUNS:
            stream = nt.RUN_SPEC[r][1]
            rec = recorded_top1(c, stream) if r != "counterfactual" else None
            s = metas[r]["sanity"]
            w_(f"| {c['id']} | {r} | {metas[r]['nTokens']} | {s['top1Agreement']:.3f} | {fmt(rec, 3)} "
               f"| {s['meanLogprobRecorded']:.3f} | {metas[r]['forwardSeconds']:.2f} |")
    w_("")
    return "\n".join(out)


def main() -> None:
    body = analyse()
    path = config.OUT_DIR / "neuron-findings.md"
    head, sep, rest = (path.read_text().partition("<!-- generated -->") if path.exists() else ("", "", ""))
    path.write_text((head + sep + "\n" if sep else "<!-- generated -->\n") + body + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
